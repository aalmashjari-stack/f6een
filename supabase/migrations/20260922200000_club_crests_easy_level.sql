-- «شعارات أندية»: ثمانية شعاراتٍ من «متوسط» إلى «سهل» (٢٢ سبتمبر ٢٠٢٦، حدّ الخليّة 30).
-- «سهل» كان 22 والأندية الأوروبيّة الأشهر كلّها فيه؛ والشعارات الجديدة المتاحة
-- (سندرلاند، بيرنلي، برينتفورد، ديبورتيفو، بوردو، بلاكبيرن، ميدلزبره، نوريتش)
-- في شهرة «متوسط» لا «سهل». فالأشهر من «متوسط» ينزل درجة، والجديدة تُرسل مسوّدات
-- «متوسط» — فيبلغ «سهل» 30 ويعود «متوسط» إلى 34 بعد الاعتماد (26 حتى ذلك، فوق حدّ العشرين).

update public.question_overrides
   set level = 'سهل', updated_at = now()
 where category = 'شعارات أندية'
   and level = 'متوسط'
   and question_id in ('ADM6739', 'ADM6740', 'ADM6745', 'ADM6747', 'ADM6748', 'ADM6750', 'ADM6751', 'ADM6752');
