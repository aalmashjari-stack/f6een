-- **بذرةُ التصنيفات الخمسة** — قسمةُ الفئات الموجودة على مظلّاتها
-- (قرار علي ١٠ سبتمبر ٢٠٢٦: «سوّ المظلّات بناءً على الفئات الموجودة»).
--
-- بذرةٌ لا عقد: كلُّ سطرٍ هنا يُغيَّر من اللوحة بضغطتين — تسميةً ونقلاً
-- وحذفاً وترتيباً. وما وُضع في الشيفرة هو الحالةُ الأولى وحدها، كي لا
-- يفتح المدير خمس عشرة قائمة بيده في أوّل يوم.
--
-- وتُطبَّق مرّةً واحدة بأثرٍ ثابت: التصنيف الموجود لا يُكرَّر، والفئة التي
-- نُقلت من اللوحة بعدها **تُعاد إلى مكانها الأوّل إن أُعيد تشغيلها** — وهذا
-- ثمنُ `do update` المقصود: بذرةٌ تُترك ولا تُشغَّل مرّتين.

/* ═══════════ الخمس ═══════════ */

insert into public.category_groups (name, sort) values
  ('ثقافة عامة', 0),
  ('علوم وصحة',  1),
  ('دين وتراث',  2),
  ('فنّ وترفيه', 3),
  ('رياضة',      4)
on conflict (name) do nothing;

/* ═══════════ الفئات المشحونة ═══════════ */
/* الصفّ يُنشأ هنا لأنّ فئة البنك ليست في هذا الجدول أصلاً — و`is_extra=false`
   يمنعها أن تُعدّ فئةً مضافة فتظهر مرّتين في شاشة اللاعب (انظر
   `20260831090100_category_art.sql`). */

insert into public.categories (name, group_name, is_extra) values
  ('جغرافيا ومعالم', 'ثقافة عامة', false),
  ('تاريخ وحضارات',  'ثقافة عامة', false),
  ('أدب وفنون',      'ثقافة عامة', false),

  ('علوم واختراعات', 'علوم وصحة',  false),
  ('أحياء وفلك',     'علوم وصحة',  false),
  ('طب وصحة',        'علوم وصحة',  false),
  ('تقنية ومنوعات',  'علوم وصحة',  false),

  ('دين وسيرة',      'دين وتراث',  false),
  ('الكويت',         'دين وتراث',  false),
  ('أمثال وألغاز',   'دين وتراث',  false),

  ('سينما ودراما',   'فنّ وترفيه', false),
  ('مشاهير',         'فنّ وترفيه', false),
  ('من أنا؟',        'فنّ وترفيه', false),

  ('رياضة وأرقام',   'رياضة',      false)
on conflict (name) do update set group_name = excluded.group_name;

/* ═══════════ ما أُضيف من اللوحة ═══════════ */
/* **تحديثٌ لا إدراج**: أسماء هذه ليست في الملفّ المشحون، فلا تُقرأ من هنا
   ولا تُخمَّن. فلو خالف الاسمُ لم يقع شيء — بدل أن يُخلق صفٌّ لفئةٍ شبحيّة
   لا سؤال تحتها. وقد وقع ذلك فعلاً: كُتب «زمن جميل» واسمُها الحيّ «الزمن
   الجميل»، فمرّت البذرةُ عليها ولم تصبها — وهذا عملُ التحديث لا خللُه.
   والأسماء الخمسة أدناه مقروءةٌ من القاعدة الحيّة في ١٠ سبتمبر ٢٠٢٦.
   وما بقي بلا مظلّة يظهر في «متفرّقات» آخرَ شاشة الإعداد، ويُنقل من
   اللوحة متى شئت. */

update public.categories set group_name = 'ثقافة عامة' where name = 'معالم';
update public.categories set group_name = 'فنّ وترفيه' where name = 'الزمن الجميل';
update public.categories set group_name = 'فنّ وترفيه' where name = 'أغاني وطرب';
update public.categories set group_name = 'دين وتراث'  where name = 'أكلات';
update public.categories set group_name = 'علوم وصحة'  where name = 'سيارات';
