/*
   **عائلاتُ الأجوبة المشتركة مع فئة «إيموجي»** — ١٥ سبتمبر ٢٠٢٦.

   فئة «إيموجي» (دفعة في المسوّدات تنتظر الاعتماد) سؤالُها رموزٌ وجوابُها
   عنوانُ فيلمٍ أو كتاب. وأحدَ عشرَ من عناوينها أجوبةٌ قائمة في البنك لوقائعَ
   أخرى («ما فيلم ديزني الذي بطله سيمبا؟ → الأسد الملك») — والجواب الواحد
   لواقعتين لا يُحذف بل **تُصرَّح عائلته** فلا يجتمعان في جلسة (قاعدة ٤
   سبتمبر). مسوّداتُ «إيموجي» تحمل العائلة في عمودها، وهذه الهجرة تضع
   العائلةَ نفسها على الطرف القائم — لأنّ «رفع ملفّ» لا يقرأ عمود العائلة،
   ولا يبقى غيرُ تعديل أحدَ عشرَ سؤالاً بيد علي واحداً واحداً.

   المفتاحُ هو الجواب كما هو مكتوب في المسوّدة حرفاً بحرف: المحرّك يقارن
   `'موضوع:' || family` نصّاً لا تطبيعاً. ولا ضررَ إن رُفضت الدفعة: عائلةٌ
   بلا شريك لا تمنع شيئاً.
*/

update public.question_overrides set family = v.f, updated_at = now()
  from (values
    ('E321', 'الأسد الملك'),
    ('E317', 'تايتانيك'),
    ('E485', 'فروزن'),
    ('E320', 'هاري بوتر'),
    ('E481', 'كونغ فو باندا'),
    ('M573', 'ماتريكس'),
    ('M577', 'سيد الخواتم'),
    ('L022', 'كليلة ودمنة'),
    ('E137', 'ألف ليلة وليلة'),
    ('M209', 'بين القصرين'),
    ('M206', 'الأيام')
  ) as v(id, f)
 where question_overrides.question_id = v.id
   and question_overrides.family is null;
