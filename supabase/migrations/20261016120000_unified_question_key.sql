/*
   مفتاحُ السؤال الموحّد — ١٦ أكتوبر ٢٠٢٦.

   `norm_question` حارسُ «النصّ موجود» في رفع الملفّ والحفظ واعتماد المسوّدات،
   ومعاينةُ «رفع ملفّ» في اللوحة تفرز بتطبيعٍ آخر في المتصفّح. وكانا مختلفين:

   - هنا كانت التاء المربوطة تصير ياءً — `translate('أإآةى','ااايي')` يقابل
     الحرفَ الرابع بالرابع — والتعليقُ فوقها يقول «هاءً». والمعاينة هاءً.
   - المعاينة كانت تحذف الإيموجي فتردّ أسئلة «إيموجي» كلّها إلّا واحداً في
     كلّ ذيل؛ وهنا تبقى. (الخلل في المعاينة، وأُصلح في المتصفّح.)
   - ولا أحدٌ منهما يرى «سنة 1920» و«سنة ١٩٢٠» سؤالاً واحداً.

   فالتعريف صار جدولَ حروفٍ واحداً في `src/lib/questionKey.ts`، وهذا الجسمُ
   مولَّدٌ منه بـ`sqlNormQuestion()` — نداءُ `translate()` واحد: ما يقابله
   حرفٌ يُستبدل، وما زاد يُحذف. بلا `[:punct:]` ولا `\s` لأنّهما يتبعان
   إعدادات القاعدة، والجدولُ لا يتبع شيئاً. و`questionKey.test.ts` يُسقط البناء
   إن اختلف هذا الجسمُ عمّا يولّده الجدول.

   قِيس الأثرُ على 7613 نصّاً (البنك والتقارير): لا تكرارَ جديداً إلّا 21
   زوجاً فرقُهما شكلُ الأرقام، ولا تكرارَ قديمٌ يسقط؛ وأثرُ «ة» صفر.

   **والفهرس يُعاد بناؤه**: `question_overrides_norm_question_idx` فهرسٌ على
   هذا التعبير (`20260915110000`)، وPostgres لا يحدّثه حين يتغيّر جسمُ دالّةٍ
   `immutable` — فيبقى بالمفاتيح القديمة، ويجيب البحثُ بالفهرس بغير ما يجيب
   به الحساب.
*/

