-- نبذة الفئة وسؤالها المثال — علامة (i) على بطاقة الفئة في الإعداد
-- (طلب علي ٢٤ سبتمبر ٢٠٢٦).
--
-- ثلاثة أعمدة على `categories`: النبذة، والسؤال المثال، وجوابه. **والسؤال
-- مكتوبٌ للنبذة وحدها لا مسحوبٌ من البنك** (قرار علي): ما يُعرض قبل اللعب
-- لا يُلعب، فلا يُحرق على المجلس سؤالٌ قد يخرج له بعد دقائق. وفي فئات الصور
-- يصف السؤالُ شكلَ السؤال، والجوابُ فارغ.
--
-- والمسوّدات الأولى كتبتُها (بموافقته) ويحرّرها من لسان «الفئات» في اللوحة.
-- والفئة بلا نبذة لا علامة عليها.

alter table public.categories
  add column if not exists info_brief text,
  add column if not exists info_q     text,
  add column if not exists info_a     text;

comment on column public.categories.info_brief is
  'نبذة الفئة في لوح (i) بالإعداد. null = لا علامة على البطاقة.';
comment on column public.categories.info_q is
  'السؤال المثال — مكتوبٌ للنبذة، ليس في البنك. في فئات الصور وصفٌ لشكل السؤال.';
comment on column public.categories.info_a is
  'جواب السؤال المثال، يُكشف بضغطة. null في فئات الصور.';

/* الكاتب من اللوحة. والفئة المشحونة بلا صفّ يُنشأ صفُّها كما في
   `admin_set_category_hidden`. والنصّ الفارغ يُحفظ null: نبذةٌ فارغة تُسقط
   العلامة لا تفتح لوحاً خالياً. */
create or replace function public.admin_set_category_info(
  p_name text, p_brief text, p_q text, p_a text
)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  clean text := btrim(coalesce(p_name, ''));
begin
  if not public.is_admin() then
    raise exception 'not_admin';
  end if;

  if clean = '' then
    raise exception 'no_such_category';
  end if;

  insert into public.categories (name, is_extra, created_by, info_brief, info_q, info_a)
  values (
    clean, false, (select auth.uid()),
    nullif(btrim(coalesce(p_brief, '')), ''),
    nullif(btrim(coalesce(p_q, '')), ''),
    nullif(btrim(coalesce(p_a, '')), '')
  )
  on conflict (name) do update
    set info_brief = excluded.info_brief,
        info_q     = excluded.info_q,
        info_a     = excluded.info_a;

  return clean;
end;
$$;

revoke execute on function public.admin_set_category_info(text, text, text, text) from public, anon;
grant  execute on function public.admin_set_category_info(text, text, text, text) to authenticated;

/* القارئ للاعب واللوحة — يحمل الأعمدة الجديدة. شكل الإرجاع تغيّر فتُسقط وتُعاد. */
drop function if exists public.extra_categories();

create function public.extra_categories()
returns table (
  name text, art_url text, is_extra boolean, group_name text, group_sort integer,
  derby boolean, hidden boolean, sort integer,
  info_brief text, info_q text, info_a text
)
language sql
stable
security definer
set search_path = ''
as $$
  select c.name, c.art_url, c.is_extra, c.group_name, g.sort, c.derby, c.hidden, c.sort,
         c.info_brief, c.info_q, c.info_a
  from public.categories c
  left join public.category_groups g on g.name = c.group_name
  order by c.created_at;
$$;

