  'الفئات المضافة وصفوفُ الصور البديلة، ومعها تصنيفُ كلٍّ وترتيبُه وعضويّتُه في الديربي واستبعادُه المؤقّت من اللوح وموضعُ الفئة داخل تصنيفها ونبذتُها وسؤالُها المثال. يقرؤها اللاعب واللوحة معاً.';

revoke execute on function public.extra_categories() from public, anon;
grant  execute on function public.extra_categories() to authenticated;

