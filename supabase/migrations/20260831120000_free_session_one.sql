-- الجلسة المجانية صارت واحدة لا اثنتين — قرار علي (٣١ أغسطس ٢٠٢٦، SPEC ٩).
--
-- الافتراض وحده يتغيّر، والحسابات القائمة تُترك كما هي: من سجّل على وعد
-- الجلستين لا يُسحب منه ما وُعد به. ولذلك `set default` لا `update`.
--
-- ولا يُعدَّل `…_profiles.sql` نفسه: هجرةٌ طُبِّقت لا تُعاد كتابتها، وإلا
-- افترقت القاعدة الحيّة عن الملفّات التي يُفترض أنّها تبنيها.

alter table public.profiles
  alter column games_balance set default 1;

comment on column public.profiles.games_balance is
  'رصيد الألعاب. الحساب الجديد يبدأ بجلسة مجانية واحدة كاملة (SPEC ٩) — ولهذا الافتراض 1 لا 0.';
