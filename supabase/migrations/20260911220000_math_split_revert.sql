-- رجوعٌ عن فصل «رياضيات» (قرار علي ١١ سبتمبر ٢٠٢٦: «مو لازم»).
--
-- رفض علي الفئات الثلاث (رياضيات · ظواهر طبيعيّة · استكشاف الفضاء) وحذف
-- الأخيرتين من اللوحة ورفض دفعاتها. وبقيت «رياضيات» لأنّ فيها التسعة
-- والستّين المنقولة من «رياضة وأرقام» — بلا تعجيزي، فلا تُلعب ولا تُحذف.
-- فتعود الأسئلة إلى فئتها الأصليّة كما كانت، وتُحذف الفئة الفارغة.

update public.question_overrides
   set category = 'رياضة وأرقام'
 where category = 'رياضيات';

delete from public.categories where name = 'رياضيات'
  and not exists (select 1 from public.question_overrides where category = 'رياضيات');
