-- سحبُ تعجيزيّ فئتي «بنات» من المسوّدات (١٩ سبتمبر ٢٠٢٦).
--
-- قال علي: «استبدل الأسئلة التعجيزية كلها، لا تحطّ أسامي صعبة مثل من المؤسّس
-- ومثل في أيّ سنة — هذه أسئلة محد يجاوب عليها، وقلت لك هذا الكلام قبل على
-- فئة الزمن الجميل». فالأربعون القديمة (عطّار شانيل، الاسم الحقيقيّ لكوكو،
-- مصمّم المونوغرام…) تُحذف من دفعتَيها المعلَّقتين، وبدائلها — عطورٌ وحقائب
-- نادرة بالصورة — تُلحَق بالدفعتين نفسيهما فيرى علي صفّاً واحداً لكلّ فئة.
-- مفتاحُ الوكيل لا يحذف ولا ينقل، فالعمل هجرةٌ مكتوبة.

delete from public.question_drafts
 where status = 'pending'
   and level = 'تعجيزي'
   and batch in ('6b512884-865b-4aaa-b6d1-a7ca700d9c5d', '3dd65f1f-ff52-43c7-b105-cf04c7b23c1f');

