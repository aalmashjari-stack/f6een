-- فئة «ولا كلمة» — تمثيلٌ صامت والكلمة في هاتف الممثّل وحده (قرار علي ٢٠
-- سبتمبر ٢٠٢٦، SPEC §٤). **تجريبيّة**: «لازم أجرّبها قبل اعتمادها رسمياً».
--
-- فتُنشأ **مستبعَدةً من اللوح** (`hidden = true`، SPEC §٧): لا تدخل إعداد
-- اللاعبين حتى يلعبها علي على تلفزيون ويرفع العلم من اللوحة بضغطة — لا
-- بشيفرةٍ خاصّة ولا بإصدار. وخارج الديربي والحق ما تلحق (`derby = false`):
-- تمثيلٌ لا يُضغط في ثلاثين ثانية، ولا يصلح جواباً منطوقاً.
--
-- تحت مظلّة «منوعات» مع «حروف» — فئتا قالبٍ لا موضوع؛ وتُنقل من اللوحة
-- كغيرها. وأسئلتُها تصل من طبقة المسوّدات بعد الفحص واعتمادِ علي، لا من هنا.

insert into public.categories (name, group_name, is_extra, derby, hidden) values
  ('ولا كلمة', 'منوعات', true, false, true)
on conflict (name) do update
  set group_name = excluded.group_name,
      hidden     = excluded.hidden,
      derby      = excluded.derby;
