--
-- أُنشئت في `20260913200000_qaael_category.sql` واعتُمدت خلاياها كاملة
-- (20 × 4) من دفعتَي المسوّدات `77fdee30` و`4cdf02c7`. ثمّ قِيست فوجدت:
-- 14 من 80 جوابها «المتنبي» — شكلٌ واحد يتكرّر حتى يُحفظ لا يُعرف — والفئة
-- صعبة لا طلب عليها في المجلس. فتُحذف بأسئلتها.
