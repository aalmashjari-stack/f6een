-- والمسوّدات الثمانون تُردّ إلى «مرفوضة» ولا تُحذف: المرفوضة مرجعُ فحص
-- التكرار في `check-drafts`، فلا يُقترح البيت نفسه في فئةٍ أخرى بلا أن
-- يُرى أنّه سبق ورُفض.

delete from public.question_overrides o
 where o.category = 'من القائل؟';

