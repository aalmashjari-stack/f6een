-- إعادة تسمية فئة «دين وسيرة» إلى «إسلامي» (قرار علي ١٤ سبتمبر ٢٠٢٦).
--
-- الفئة كانت تُعرض باسم «إسلاميات» وهو اسم مظلّتها منذ ١١ سبتمبر، فالتبست
-- بها. وأراد علي الاسمَ الحقيقيَّ لا اسمَ العرض.
--
-- وثيقة `categories` تقول إنّ إعادة التسمية ليست عمليّة لأنّ الاسم في
-- مكانين لا يعرف أحدهما الآخر: القاعدة والملفّ المشحون. وهنا يُغيَّر
-- المكانان في الدفعة نفسها — هذه الهجرة للقاعدة، والملفّ وخريطة الصور
-- ومسمّيات العرض في الكود معها في الـcommit نفسه.
--
-- الاسم ليس مفتاحاً أجنبيّاً في أيّ جدول، فلا تتالي؛ والثلاثة تُعدَّل
-- صراحةً. و`updated_at` تُرفع لأنّ `bank_signature` تقرأ أقصاها — وبغيرها
-- تبقى نسخة كلّ لاعب على الاسم القديم حتى يتغيّر سؤال.

update public.categories
   set name = 'إسلامي'
 where name = 'دين وسيرة';

update public.question_overrides
   set category = 'إسلامي', updated_at = now()
 where category = 'دين وسيرة';

update public.question_drafts
   set category = 'إسلامي'
 where category = 'دين وسيرة';
