-- مظلّة «إسلاميات» (قرار علي ١١ سبتمبر ٢٠٢٦).
--
-- **بذرةٌ لا مخطّط** — وهي أوّل ما يُطبَّق عبر `npm run db:push` بدل اللصق
-- اليدويّ. وكلُّ جملةٍ فيها تُعاد بلا ضرر: التسميةُ لا تجد ما تسمّيه في
-- المرّة الثانية، والإخراجُ يُخرج ما خرج، والإدراجُ `on conflict`.
--
-- والقرار:
--   • «دين وتراث» تُعاد تسميتها «إسلاميات».
--   • تخرج منها: الكويت · أمثال وألغاز · أكلات — فهي تراثٌ لا دين.
--   • وتدخلها فئتان جديدتان: قصص الأنبياء · السيرة النبوية.
--
-- وإعادةُ التسمية آمنةٌ لأنّ اسم التصنيف لا يعرفه إلّا عمودٌ واحد، والمفتاح
-- الأجنبيّ `on update cascade` ينقله إلى فئاته. ولا سؤالَ يمسّه هذا:
-- السؤال يعرف فئتَه لا تصنيفَها.

/* ١) التسمية — تنتقل إلى الفئات وحدها بالتتالي. */
update public.category_groups set name = 'إسلاميات' where name = 'دين وتراث';

/* ٢) الثلاثُ تخرج من المظلّة ولا تُحذف — أسئلتها كما هي.
      وتقع في «متفرّقات» آخرَ شاشة الإعداد حتى تُعطى مظلّةً جديدة. */
update public.categories set group_name = null
 where name in ('الكويت', 'أمثال وألغاز', 'أكلات');

/* ٣) الفئتان الجديدتان — تُنشآن قبل الأسئلة (قرار ٣١ أغسطس)، ولا تظهران
      في الإعداد حتى تمتلئ صفوفُهما الأربعة. */
insert into public.categories (name, group_name, is_extra) values
  ('قصص الأنبياء',   'إسلاميات', true),
  ('السيرة النبوية', 'إسلاميات', true)
on conflict (name) do update set group_name = excluded.group_name;
