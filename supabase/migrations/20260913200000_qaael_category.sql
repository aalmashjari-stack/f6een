-- فئة «من القائل؟» تحت مظلّة «منوعات» (قرار علي ١٣ سبتمبر ٢٠٢٦).
--
-- فئةُ قالبٍ كـ«من أنا؟» و«حروف»: بيتٌ مشهور أو قولٌ مأثور → صاحبه.
-- قِيست قبل أن يُكتب لها سؤال: في البنك الحيّ سؤالان فقط بهذا القالب،
-- وفي «موسوعة المسابقات» باب كامل (164) خرج منه 39 بيتاً ثابتاً في دواوينه.
-- والأقوال المنثورة أُسقطت لأنّ أكثرها منحول.

insert into public.categories (name, group_name, is_extra) values
  ('من القائل؟', 'منوعات', true)
on conflict (name) do update set group_name = excluded.group_name;
