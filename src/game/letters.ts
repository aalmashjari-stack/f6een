/**
 * فئة «حروف» — أسئلةٌ عامّة يُعطى معها **الحرف الأوّل من الجواب** (قرار
 * علي ١٣ سبتمبر ٢٠٢٦).
 *
 * **الحرف يتبع السؤال لا السؤال الحرف.** الخليّة فيها عشرون سؤالاً
 * والأبجديّة ثمانيةٌ وعشرون حرفاً، فلا يمكن لكلّ حرفٍ سؤالٌ في كلّ مستوى —
 * ولو اختير الحرف أوّلاً لوقف الاختيار على «ظ» ولا سؤال لها أمام المجلس
 * (الباب نفسه الذي أقفله SPEC §٧ على الفئة الناقصة). فالمحرّك يسحب السؤال
 * كما يسحب أيّ خليّة، ويشتقّ حرفَه من جوابه، وبلاطةُ الحروف على الشاشة
 * تدور ثمّ تقف على ذلك الحرف: يرى المجلس قرعةً والنتيجة مضمونة دائماً.
 *
 * **والاسم مفتاحٌ ثابت لا يُعاد تسميته** — كأسماء الفئات كلّها: اسمُ الفئة
 * مكتوبٌ في كلّ سؤالٍ من أسئلتها (`20260830190000_categories.sql`)، فعمودُ
 * «نوع» في القاعدة كان سيحمي من تغييرٍ لا يقع. وهو الباب نفسه الذي دخلت
 * منه مواضيعُ الأمثال في `QuestionView`.
 */
export const LETTERS_CATEGORY = 'حروف'

export function isLettersCategory(category: string): boolean {
  return category === LETTERS_CATEGORY
}

/** الأبجديّة كما تُعرض على البلاطة — ثمانيةٌ وعشرون حرفاً بترتيبها. */
export const ALPHABET = [
  'ا', 'ب', 'ت', 'ث', 'ج', 'ح', 'خ', 'د', 'ذ', 'ر', 'ز', 'س', 'ش', 'ص',
  'ض', 'ط', 'ظ', 'ع', 'غ', 'ف', 'ق', 'ك', 'ل', 'م', 'ن', 'ه', 'و', 'ي',
] as const

export type Letter = (typeof ALPHABET)[number]

const LETTER_SET = new Set<string>(ALPHABET)

/** حركات وتنوين وشدّة وتطويل — لا تُحسب حرفاً. */
const MARKS = /[ً-ٰٟـ]/g

/**
 * الحرف الأوّل من الجواب بقاعدة علي (١٣ سبتمبر ٢٠٢٦):
 *
 * - **«ال» تسقط:** الرياض → ر، القاهرة → ق.
 * - **الهمزة تُطبَّع ألفاً:** أحمد وإبراهيم وآسيا → ا.
 * - **المركّب يأخذ حرف كلمته الأولى كما هي، بلا استثناء:** ابن سينا → ا،
 *   عبد الله → ع. (لا «سينا»: قال علي «لا يُقال ابن سينا والحرف هو الألف».)
 * - **ما بين القوسين لا يدخل:** «يعفور (وقيل عُفير)» → ي.
 *
 * وتعود `null` لجوابٍ لا يبدأ بحرفٍ عربيّ (رقم، لاتينيّ) — فلا بلاطة له،
 * و`check-drafts` يردّه قبل أن يصل إلى الفئة.
 */
export function firstLetter(answer: string): Letter | null {
  const s = answer.replace(/\([^)]*\)/g, ' ').replace(MARKS, '').trim()
  /* أوّل كلمةٍ فيها حرفٌ عربيّ — تُتجاوز علامات الاقتباس والشرطات قبلها. */
  const found = s.split(/\s+/).find((w) => /[ء-ي]/.test(w))
  if (!found) return null
  let word = found.replace(/^[^ء-ي]+/, '')
  /* «ال» تسقط حين يبقى بعدها حرفان فأكثر — وقبل تطبيع الهمزة: «ألمانيا»
     و«إلياس» و«ألم» ليست معرَّفةً وإن بدت كذلك بعد التطبيع. */
  if (/^[اٱ]ل/.test(word) && word.length >= 4) word = word.slice(2)
  const c = word[0]?.replace(/[أإآٱ]/, 'ا').replace('ى', 'ي').replace('ة', 'ه')
  return c !== undefined && LETTER_SET.has(c) ? (c as Letter) : null
}
