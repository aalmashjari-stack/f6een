/**
 * نص السؤال — مقاسه يتبع طوله.
 *
 * البنك كان أسئلةً قصيرة (وسيطها أربعون حرفاً) فكفاها مقاس واحد. ثم أدخلت
 * فئة «من أنا؟» أسئلةً من سطرين من السيرة الذاتية، وأطولها مئة وواحد
 * وخمسون حرفاً — بالمقاس نفسه يفيض النص عن بطاقته ويلتصق بحوافها فتفقد
 * الشاشة اتزانها.
 *
 * العتبتان مقروءتان من البنك لا مقدّرتان: تسعون بالمئة من الأسئلة دون
 * الثمانين حرفاً فتبقى على مقاسها الأصلي بلا تغيير، وسبعة بالمئة بين
 * الثمانين والمئة والعشرين، واثنان بالمئة فوقها. فالهبوط يمسّ التسعة
 * بالمئة وحدها، وأشدّ درجاته محسوبة على أطول سؤال موجود فعلاً — فيبقى
 * مقروءاً من آخر المجلس، وهو شرط تشغيل لا تفضيل جمالي (القسم ١).
 */

const LONG = 80
const EXTRA_LONG = 120

export function QuestionText({ children }: { children: string }) {
  const size = children.length > EXTRA_LONG ? ' xlong' : children.length > LONG ? ' long' : ''
  return <p className={'q-text' + size}>{children}</p>
}
